// Scale behaviour for the Photo Map. The map has to stay usable on a
// collection of photographs, which is the normal size for a phone or a
// camera card -- not an unusual one.

// p21ManyPhotos builds n located images spread over real coordinates, so
// the country lookup is exercised per photo rather than hitting one
// cached answer.
func p21ManyPhotos(n int) map[string][]byte {
	files := make(map[string][]byte, n)
	for i := 0; i < n; i++ {
		lat := uint32(i % 60)
		lon := uint32((i * 7) % 100)
		files[fmt.Sprintf("Users/j/Pictures/IMG_%04d.jpg", i)] = exifgen.Build(exifgen.Spec{
			Width: 640, Height: 480,
			Make: "ACME", Model: "Cam",
			DateTimeOriginal: fmt.Sprintf("2021:04:%02d 1%d:00:00", (i%27)+1, i%10),
			GPS: &exifgen.GPS{
				LatRef: "N", Lat: exifgen.DMS(lat, uint32(i%60), 0),
				LonRef: "E", Lon: exifgen.DMS(lon, uint32(i%60), 0),
			},
			Thumbnail: exifgen.MinimalJPEG(),
		})
	}
	return files
}

// The dataset a map load costs, measured end to end through the HTTP
// handler -- event query, country fields, collection labels, source file
// lookups and JSON encoding.
func TestPerf_PhotoMapDatasetScales(t *testing.T) {
	if testing.Short() {
		t.Skip("scale measurement skipped in -short")
	}

	for _, n := range []int{100, 500} {
		t.Run(fmt.Sprintf("%d photos", n), func(t *testing.T) {
			mux := newTestRouter(t)
			c := mustCreateCase(t, mux, fmt.Sprintf("perf %d", n))
			disc := discoverBinaryDir(t, mux, c.ID, p21ManyPhotos(n))
			if imp := importAllFrom(t, mux, c.ID, disc); len(imp.ParseFailures) != 0 {
				t.Fatalf("import failed: %+v", imp.ParseFailures)
			}

			start := time.Now()
			var res GeoPhotoResult
			rec := doJSON(t, mux, "GET", "/api/cases/"+c.ID+"/geo/photos", nil, &res)
			elapsed := time.Since(start)

			if rec.Code != http.StatusOK {
				t.Fatalf("geo/photos: %d", rec.Code)
			}
			if res.Total != n {
				t.Fatalf("got %d markers, want %d", res.Total, n)
			}
			t.Logf("%d markers in %v (%d bytes of JSON)", res.Total, elapsed, rec.Body.Len())

			// A map load must not become the slowest thing in the app.
			// Generous, because this is a correctness guard against an
			// accidental per-photo query, not a benchmark.
			if elapsed > 5*time.Second {
				t.Errorf("building %d markers took %v", n, elapsed)
			}
		})
	}
}

// Previews must be generated only for photos actually looked at. A map
// load must not produce one per photo.
func TestPerf_ThumbnailsAreNotGeneratedEagerly(t *testing.T) {
	mux, svc := newTestRouterWithService(t)
	c := mustCreateCase(t, mux, "perf lazy")
	disc := discoverBinaryDir(t, mux, c.ID, p21ManyPhotos(40))
	if imp := importAllFrom(t, mux, c.ID, disc); len(imp.ParseFailures) != 0 {
		t.Fatalf("import failed: %+v", imp.ParseFailures)
	}

	var res GeoPhotoResult
	doJSON(t, mux, "GET", "/api/cases/"+c.ID+"/geo/photos", nil, &res)
	if res.Total != 40 {
		t.Fatalf("got %d markers", res.Total)
	}

	// Nothing has been viewed, so nothing should have been generated.
	if n := p21CachedThumbnails(t, svc, c.ID); n != 0 {
		t.Errorf("%d previews were generated by a map load alone", n)
	}

	// Ask for three.
	for i := 0; i < 3; i++ {
		rec := p21GetRaw(t, mux, "/api/cases/"+c.ID+"/images/"+res.Photos[i].SourceFileID+"/thumbnail")
		if rec.Code != http.StatusOK {
			t.Fatalf("thumbnail %d: %d", i, rec.Code)
		}
	}
	if n := p21CachedThumbnails(t, svc, c.ID); n != 3 {
		t.Errorf("%d previews cached after viewing 3", n)
	}
}

// A cached preview must be served from the cache, not regenerated.
func TestPerf_ThumbnailCacheIsUsed(t *testing.T) {
	mux := newTestRouter(t)
	caseID := p21Case(t, mux)
	sfID := p21SourceFileID(t, mux, caseID, "south.jpg")
	path := "/api/cases/" + caseID + "/images/" + sfID + "/thumbnail"

	first := time.Now()
	p21GetRaw(t, mux, path)
	cold := time.Since(first)

	second := time.Now()
	rec := p21GetRaw(t, mux, path)
	warm := time.Since(second)

	if rec.Header().Get("X-Tracefall-Thumbnail-Source") != "cache" {
		t.Errorf("the second request did not come from the cache: %q",
			rec.Header().Get("X-Tracefall-Thumbnail-Source"))
	}
	t.Logf("thumbnail cold %v, warm %v", cold, warm)
}

func p21CachedThumbnails(t *testing.T, svc *Service, caseID string) int {
	t.Helper()
	dir := svc.files.DerivedDir(caseID) + "/thumbnails"
	entries, err := os.ReadDir(dir)
	if err != nil {
		return 0
	}
	return len(entries)
}
