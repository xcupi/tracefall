package model

import "time"

// User is a local Tracefall account.
//
// Tracefall has no external identity provider and this phase adds none:
// a DFIR deployment is typically one small team on an isolated network,
// and an OIDC dependency there is a liability rather than a feature.
// Accounts are local, and the model stays small enough to reason about.
type User struct {
	ID       string `json:"id"`
	Username string `json:"username"`
	Role     string `json:"role"`

	// PasswordHash is NEVER serialized. The json:"-" is the last line of
	// defence rather than the only one -- handlers return the API-facing
	// view (see api.PublicUser), not this struct -- but a struct that
	// could serialize a credential if someone marshalled it by accident
	// is a bug waiting for a careless refactor.
	PasswordHash string `json:"-"`

	CreatedAt time.Time  `json:"created_at"`
	Disabled  bool       `json:"disabled"`
	LastLogin *time.Time `json:"last_login,omitempty"`

	// MustChangePassword gates the account behind a mandatory password
	// change before it can do anything else.
	//
	// Set for the first-run bootstrap account: its password was
	// generated by the server and printed to a terminal, where it may
	// persist in scrollback, a screenshot, or a CI log. A credential
	// that has been displayed in plaintext should not stay usable
	// indefinitely, so the account can authenticate but can do nothing
	// except change it.
	MustChangePassword bool `json:"must_change_password"`
}

// Roles.
//
// Two, deliberately. Every additional role multiplies the number of
// (role x endpoint) states that have to be reasoned about and tested,
// and the distinction that actually matters in a DFIR team is between
// people who analyse evidence and people who may DESTROY it.
const (
	// RoleAnalyst may do all evidence and analysis work: create cases,
	// ingest, import, analyze, annotate, export, and verify integrity.
	RoleAnalyst = "analyst"
	// RoleAdmin additionally may delete cases and evidence and manage
	// users. Deletion is the privilege boundary because deletion is the
	// only action that destroys forensic material.
	RoleAdmin = "admin"
)

// ValidRole reports whether role is one Tracefall recognizes.
func ValidRole(role string) bool {
	return role == RoleAnalyst || role == RoleAdmin
}

// Session is one authenticated login, stored server-side.
//
// Server-side sessions rather than self-contained tokens (JWT and
// friends) because logout has to actually work: a signed token stays
// valid until it expires no matter what the server thinks, whereas a row
// can be deleted. For a tool that handles evidence, "revoke this session
// now" is worth more than statelessness.
type Session struct {
	// ID is the token HASH, never the token itself -- see
	// auth.HashSessionToken.
	ID        string    `json:"-"`
	UserID    string    `json:"-"`
	CreatedAt time.Time `json:"created_at"`
	ExpiresAt time.Time `json:"expires_at"`
}

// Audit actions for security-sensitive operations (Phase 12).
//
// Kept in the SAME audit log as the existing workflow actions rather
// than in a separate security log: an investigator reviewing what
// happened to a case needs one ordered account, not two that have to be
// interleaved by hand. They are distinguishable by action name, and
// security events that belong to no case carry an empty CaseID.
const (
	AuditLoginSucceeded  = "login_succeeded"
	AuditLoginFailed     = "login_failed"
	AuditLogout          = "logout"
	AuditUserCreated     = "user_created"
	AuditUserUpdated     = "user_updated"
	AuditUserDeleted     = "user_deleted"
	AuditAccessDenied    = "access_denied"
	AuditSessionExpired  = "session_expired"
	AuditPasswordChanged = "password_changed"
)

// TargetUser is the audit target type for account administration.
const TargetUser = "user"
